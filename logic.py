import sqlite3

# Создаём соединение с базой данных
conn = sqlite3.connect('world_cup.db')
cursor = conn.cursor()

# Очищаем таблицы, если они уже существуют
cursor.execute("DROP TABLE IF EXISTS world_cups")
cursor.execute("DROP TABLE IF EXISTS finals")
cursor.execute("DROP TABLE IF EXISTS top_scorers")

# Таблица 1: Информация о чемпионатах мира
cursor.execute('''
CREATE TABLE IF NOT EXISTS world_cups (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    year INTEGER NOT NULL,
    host_country TEXT NOT NULL,
    winner TEXT NOT NULL,
    runner_up TEXT NOT NULL,
    third_place TEXT,
    matches_played INTEGER,
    total_goals INTEGER,
    attendance INTEGER
)
''')

# Таблица 2: Счёты финалов
cursor.execute('''
CREATE TABLE IF NOT EXISTS finals (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    world_cup_id INTEGER,
    date TEXT,
    stadium TEXT,
    city TEXT,
    country TEXT,
    score TEXT NOT NULL,
    winner_goals INTEGER,
    runner_up_goals INTEGER,
    FOREIGN KEY (world_cup_id) REFERENCES world_cups(id)
)
''')

# Таблица 3: Лучшие бомбардиры каждого чемпионата
cursor.execute('''
CREATE TABLE IF NOT EXISTS top_scorers (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    world_cup_id INTEGER,
    player_name TEXT NOT NULL,
    country TEXT NOT NULL,
    goals INTEGER NOT NULL,
    FOREIGN KEY (world_cup_id) REFERENCES world_cups(id)
)
''')


